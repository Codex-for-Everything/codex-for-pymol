_locale = ZH_CN


def normalize_locale(value, system_locale=""):
    value = str(value or "")
    if value in SUPPORTED_LOCALES:
        return value
    candidate = str(system_locale or value).replace("-", "_").lower()
    return ZH_CN if candidate.startswith("zh") else EN


def set_locale(locale):
    global _locale
    _locale = normalize_locale(locale)
    return _locale


def get_locale():
    return _locale


def text(key, **params):
    catalog = CATALOGS.get(_locale, CATALOGS[EN])
    template = catalog.get(key, CATALOGS[EN].get(key, key))
    return template.format(**params) if params else template


def placeholders(template):
    return {
        field_name
        for _literal, field_name, _format_spec, _conversion
        in Formatter().parse(template)
        if field_name
    }
